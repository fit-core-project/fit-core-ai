def _units_ok(unit, explicit):
    if explicit:
        return list(explicit)
    if unit is None:
        return []
    out = {unit}
    for grp in _SYN_GROUPS:
        if unit in grp:
            out |= grp
    return sorted(out)


SPLIT_SALT = "fitcore-diet-v1"


def _split(case_id: str) -> str:
    """Stable split: sha1(salt:id) parity. Never depends on case order or content."""
    digest = hashlib.sha1(f"{SPLIT_SALT}:{case_id}".encode("utf-8")).hexdigest()
    return "dev" if int(digest, 16) % 2 == 0 else "test"


def main():
    rows = {r["food_id"]: r for r in csv.DictReader(CSV_PATH.open(encoding="utf-8-sig"))}
    out = []
    for n, spec in enumerate(CASES, 1):
        cid = f"dv1_{n:03d}"
        text = spec["text"]
        assert text not in SCRATCH_INPUTS, f"scratch input reused verbatim: {text}"
        items_out = []
        tags = set()
        for it in spec["items"]:
            f = R[it["key"]]
            tags.add(f"group:{f['group']}")
            amt, unit = it["amt"], it["unit"]
            # literal amount range
            if amt is None:
                amount = None
            elif isinstance(amt, tuple):
                amount = [float(amt[0]), float(amt[1])]
            else:
                amount = [round(float(amt), 4), round(float(amt), 4)]
            # unit tag
            if amt is None:
                tags.add("unit:숫자없음")
            elif isinstance(amt, tuple):
                tags.add("unit:범위")
            elif float(amt) < 1:
                tags.add("unit:반" if abs(float(amt) - 0.5) < 1e-9 else "unit:분수")
            if unit:
                tags.add(f"unit:{UNIT_TAGS.get(unit, unit)}")
            # grams
            if it["grams"] is not None:
                g_lo, g_hi = it["grams"]
                g_basis = f"{g_lo}-{g_hi}g (case-specific)"
            elif amt is None:
                g_lo, g_hi = f["serving"]
                g_basis = f"1회 제공량 {g_lo}-{g_hi}g"
            else:
                a_lo, a_hi = amount
                if unit in ("g", "ml"):
                    g_lo, g_hi = a_lo * 0.98, a_hi * 1.02
                    g_basis = f"{a_lo:g}-{a_hi:g}{unit}"
                elif unit == "cm":
                    per = f["units"]["cm"]
                    g_lo, g_hi = it["grams"] if it["grams"] else (a_lo / 15 * f["serving"][0], a_hi / 15 * f["serving"][1])
                    g_basis = f"{a_lo:g}cm"
                else:
                    per = f["units"][unit]
                    g_lo, g_hi = a_lo * per[0], a_hi * per[1]
                    g_basis = f"{a_lo:g}-{a_hi:g}{unit} x {per[0]}-{per[1]}g"
            g_lo, g_hi = round(g_lo, 1), round(g_hi, 1)
            # kcal densities
            dens, parts = [], []
            for gid in f["gold"]:
                if gid == "curated":
                    k = CURATED_KCAL[f["curated"]]
                    dens.append(k)
                    parts.append(f"curated:{f['curated']} {k}kcal/100(4/4/9)")
                elif gid == LLM:
                    if f["est"] is not None:
                        dens += list(f["est"])
                        parts.append(f"label {f['est'][0]}-{f['est'][1]}kcal/100" + (f" ({f['est_basis']})" if f["est_basis"] else ""))
                else:
                    assert gid in rows, f"{cid}: unknown food_id {gid}"
                    k = float(rows[gid]["kcal"])
                    dens.append(k)
                    parts.append(f"{gid}[{rows[gid]['name']}] {k:g}kcal/100{rows[gid]['basis_unit']}")
            assert dens, f"{cid}: no kcal basis for {it['key']}"
            k_lo = max(0.0, min(dens) * g_lo / 100 * (1 - KCAL_TOL) - KCAL_ABS)
            k_hi = max(dens) * g_hi / 100 * (1 + KCAL_TOL) + KCAL_ABS
            basis = f"{' | '.join(parts)} x {g_basis} (+-10%, +-5kcal)"
            if f.get("note"):
                basis += f"; {f['note']}"
            if it.get("note"):
                basis += f"; {it['note']}"
            items_out.append({
                "key": it["key"],
                "names": f["names"],
                "gold_food_ids": f["gold"],
                "amount": amount,
                "units": _units_ok(unit, it["units_ok"]),
                "grams": [g_lo, g_hi],
                "kcal": [round(k_lo, 1), round(k_hi, 1)],
                "basis": basis,
                "optional": bool(it["optional"]),
                "low_discrimination": bool(k_lo > 0 and k_hi / k_lo > 3.0),
            })
        req = [i for i in items_out if not i["optional"]]
        n_req = len(req)
        tags.add("items:" + ("0" if n_req == 0 else "1" if n_req == 1 else "2" if n_req == 2 else "3+"))
        for nz in spec["noise"]:
            tags.add(f"noise:{nz}")
        if not spec["noise"]:
            tags.add("noise:없음")
        if _HANGUL_NUM_RE.search(text):
            tags.add("unit:한글숫자")
        for t in spec["extra_tags"]:
            tags.add(t if ":" in t else f"flag:{t}")
        total_lo = round(sum(i["kcal"][0] for i in req), 1)
        total_hi = round(sum(i["kcal"][1] for i in items_out), 1)
        out.append({
            "id": cid,
            "text": text,
            "split": _split(cid),
            "tags": sorted(tags),
            "expected_items": items_out,
            "expected_item_count": {
                "min": spec["min_items"] if spec["min_items"] is not None else n_req,
                "max": spec["max_items"] if spec["max_items"] is not None else len(items_out),
            },
            "total_kcal": [total_lo, total_hi],
            "label_confidence": spec["conf"],
            "note": spec["note"],
        })
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with OUT_PATH.open("w", encoding="utf-8", newline="\n") as fh:
        for row in out:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
    # summary
    from collections import Counter
    sp = Counter(r["split"] for r in out)
    tg = Counter(t for r in out for t in r["tags"])
    print(f"wrote {len(out)} cases -> {OUT_PATH} splits={dict(sp)}")
    for t, c in sorted(tg.items()):
        print(f"  {t}: {c}")


if __name__ == "__main__":
    main()
